/**
 * Точка отсчёта времени для всех демо-данных.
 *
 * Берём реальную дату, приведённую к полудню: календарь бронирования не
 * предлагает прошедшие даты, отзывы и уведомления выглядят свежими, а внутри
 * одних суток генерация остаётся детерминированной.
 *
 * При переходе на реальную БД этот модуль удаляется — время будет приходить
 * из данных.
 */
export function startOfToday(): Date {
  const now = new Date();
  return new Date(now.getFullYear(), now.getMonth(), now.getDate(), 12, 0, 0, 0);
}

export const DEMO_NOW = startOfToday();
