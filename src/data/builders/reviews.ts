function ratingToBand(rating: number): keyof typeof BODIES {
  if (rating >= 4.5) return 'great';
  if (rating >= 4) return 'good';
  if (rating >= 3) return 'mixed';
  return 'bad';
}

/**
 * Даты отзывов распределяем за последние ~18 месяцев,
 * свежие — чаще (эффект живой площадки).
 */
function reviewDate(random: () => number, index: number) {
  const daysAgo = Math.round((random() ** 2) * 540) + index;
  const date = new Date(DEMO_NOW);
  date.setDate(date.getDate() - daysAgo);
  return date.toISOString();
}

/**
 * Генерирует отзывы для заведения. Средняя оценка сгенерированных отзывов
 * согласована с venue.rating.score — витрина и детальная страница не противоречат друг другу.
 */
export function buildReviews(venue: Venue, count: number): Review[] {
  const random = createRandom(hashString(`${venue.slug}-reviews`));
  const reviews: Review[] = [];

  for (let index = 0; index < count; index += 1) {
    // Оценка колеблется вокруг среднего рейтинга заведения.
    const noise = (random() + random() + random()) / 3 - 0.5;
    const rating = clamp(Math.round(venue.rating.score + noise * 2.6), 1, 5);
    const band = ratingToBand(rating);

    const authorName = `${pick(FIRST_NAMES, random)} ${pick(LAST_NAMES, random)}`;
    const createdAt = reviewDate(random, index);
    const hasReply = band === 'bad' ? random() > 0.25 : random() > 0.62;

    reviews.push({
      id: `${venue.slug}-review-${index + 1}`,
      venueId: venue.id,
      author: {
        id: `reviewer-${hashString(authorName + index)}`,
        name: authorName,
        avatar: `/api/avatar/${encodeURIComponent(authorName)}-${index}/96`,
        reviewsCount: 1 + Math.floor(random() * 48),
        isVerified: random() > 0.35,
      },
      rating,
      ratings: {
        food: clamp(Math.round(rating + (random() - 0.5) * 1.4), 1, 5),
        service: clamp(Math.round(rating + (random() - 0.5) * 1.8), 1, 5),
        atmosphere: clamp(Math.round(rating + (random() - 0.5) * 1.2), 1, 5),
        price: clamp(Math.round(rating + (random() - 0.5) * 2), 1, 5),
      },
      title: pick(TITLES[band], random),
      text: pick(BODIES[band], random),
      photos:
        random() > 0.72
          ? Array.from({ length: 1 + Math.floor(random() * 3) }, (_, photoIndex) =>
              `https://images.unsplash.com/photo-1555939594-58d7cb561ad1?w=500&h=500&fit=crop&q=80&sig=${venue.slug}-r${index}-${photoIndex}`,
            )
          : [],
      likes: Math.floor(random() ** 2 * 64),
      occasion: pick(OCCASIONS, random),
      reply: hasReply
        ? {
            id: `${venue.slug}-review-${index + 1}-reply`,
            businessId: venue.businessId,
            businessName: venue.name,
            text: band === 'bad' || band === 'mixed' ? REPLIES[1] : pick(REPLIES.slice(0, 3), random),
            createdAt: new Date(
              new Date(createdAt).getTime() + (2 + random() * 40) * 3600 * 1000,
            ).toISOString(),
          }
        : undefined,
      createdAt,
      updatedAt: createdAt,
    });
  }

  return reviews.sort(
    (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime(),
  );
}
